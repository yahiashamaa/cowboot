#include "./include/asm/regdef.h"

	.set noreorder

	.globl _start
	.text
_start:

	bal		1f
	 nop
	.word	_gp
1:

	lw		gp, 0(ra)
	li		sp, 0x80400000 	# temporary stack pointer

	la  	t9, early_init
	jr  	t9
	 nop	


	.globl	relocate_code
	.ent	relocate_code
relocate_code:
	move	sp, a0			# set new stack pointer


	li		t0, 0x80F00000  # source (our textbase)
	move	t1, a2 			# destination (new textbase)
	la  	t2, __image_copy_end # end of source

	subu	t3, t2, t0		# length
	addu	t4, t1, t3		# dst end
	subu	t5, a2, t0		# relocation offset

	addu 	gp, gp, t5		# adjust gp

copy_loop:
	lw		t6, 0(t0)
	sw		t6, 0(t1)
	addu	t0, t0, 4
	blt		t0, t2, copy_loop
	 addu	t1, t1, 4


	# flush dcache
	li		t0, 0x80F00000  		# start
	li 		t1, 0x80F00000 + 32768

flush_dcache_loop:
	cache	0x01, 0(t0)
	addi	t0, t0, 32	# CONFIG_SYS_CACHELINE_SIZE
	 blt	t0, t1, flush_dcache_loop
	  nop
	sync



	# flush icache
	li		t0, 0x80F00000
	

flush_icache_loop:
	cache	0x00, 0(t0)
	addi	t0, t0, 32
	blt		t0, t1, flush_icache_loop
	 nop


	# Invalidate BTB
	mfc0	t0, CP0_CONFIG, 7
	nop
	ori		t0, t0, 2
	mtc0	t0, CP0_CONFIG, 7
	nop

	# Jump to our relocated self
	li		t0, relocated_self - _start
	addu	t0, t0, a2
	jr		t0
	 nop

	.word	__rel_dyn_end
	.word	__rel_dyn_start
	.word	__image_copy_end
	.word	_GLOBAL_OFFSET_TABLE_
	.word	num_got_entries

relocated_self:
	/*
	 * Now we want to update GOT.
	 *
	 * GOT[0] is reserved. GOT[1] is also reserved for the dynamic object
	 * generated by GNU ld. Skip these reserved entries from relocation.
	 */

	lw		t3, -4(t0)		# t3 <-- num_got_entries
	lw		t4, -8(t0)		# t4 <-- _GLOBAL_OFFSET_TABLE_
	add		t4, t5			# t4 now holds relocated _G_O_T_
	addi	t4, t4, 8		# skipping first two entries
	li		t2, 2

reloc_got_loop:
	lw		t1, 0(t4)
	beqz	t1, reloc_got_next
	 add	t1, t5
	sw		t1, 0(t4)

reloc_got_next:
	addi	t2, t2, 1
	blt		t2, t3, reloc_got_loop
	 addi	t4, t4, 4

	/* Update dynamic relocations */
	lw		t1, -16(t0)		# t1 <-- __rel_dyn_start
	lw		t2, -20(t0)		# t2 <-- __rel_dyn_end

	b		reloc_dyn_next			# skip first reserved entry
	 addi	t1, 8

reloc_dyn_loop:
	lw		t3, -4(t1)		# t3 <-- relocation info

	subu	t3,	t3, 3
	bnez	t3, reloc_dyn_next			# skip non R_MIPS_REL32 entries
	 nop

	lw		t3, -8(t1)		# t3 <-- location to fix up in FLASH

	lw		t4, 0(t3)		# t4 <-- original pointer
	addu	t4,	t4, t5			# t4 <-- adjusted pointer

	addu	t3,	t3, t5			# t3 <-- location to fix up in RAM
	sw		t4, 0(t3)

reloc_dyn_next:
	addi	t1, t1, 8			# each rel.dyn entry is 8 bytes
	blt		t1, t2, reloc_dyn_loop
	 nop

	# clear bss
	la		t0, __bss_start
	la		t1, __bss_end

clear_bss:
	sw		zero, 0(t0)
	addi	t0, t0, 4
	blt		t0, t1, clear_bss
	 nop


	# jump to main, can't be more obvious, no?
	la		t9, main
	jr		t9
	 nop

	.end relocate_code

